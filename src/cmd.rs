/// Global key bindings. Editing keys (arrows, typing, …) are handled by the
/// editor itself; this only maps shortcuts to commands.
pub fn keymap(key: Key, m: Mods) -> Option<Cmd> {
    let c = |ctrl: bool, shift: bool, alt: bool| m.ctrl == ctrl && m.shift == shift && m.alt == alt;
    Some(match key {
        Key::Char(ch) => {
            let ch = ch.to_ascii_lowercase();
            if m.ctrl && !m.alt {
                match (ch, m.shift) {
                    ('n', false) | ('t', false) => Cmd::NewTab,
                    ('o', false) => Cmd::OpenFile,
                    ('s', false) => Cmd::Save,
                    ('s', true) => Cmd::SaveAs,
                    ('w', false) => Cmd::CloseTab,
                    ('w', true) => Cmd::ReopenTab,
                    ('t', true) => Cmd::Themes,
                    ('z', false) => Cmd::Undo,
                    ('z', true) | ('y', false) => Cmd::Redo,
                    ('x', false) => Cmd::Cut,
                    ('c', false) => Cmd::Copy,
                    ('c', true) => Cmd::SyntaxColors,
                    ('m', true) => Cmd::ToggleMdPreview,
                    ('v', false) => Cmd::Paste,
                    ('a', false) => Cmd::SelectAll,
                    ('d', _) => Cmd::DuplicateLine,
                    ('k', true) => Cmd::DeleteLine,
                    ('/', _) => Cmd::ToggleComment,
                    (']', _) | ('}', _) => Cmd::Indent,
                    ('[', _) | ('{', _) => Cmd::Outdent,
                    ('f', false) => Cmd::Find,
                    ('h', false) => Cmd::Replace,
                    ('g', false) => Cmd::GotoLine,
                    ('p', true) => Cmd::Palette,
                    ('p', false) => Cmd::QuickOpen,
                    (',', _) => Cmd::Settings,
                    ('\\', false) => Cmd::SplitRight,
                    ('|', _) | ('\\', true) => Cmd::SplitDown,
                    ('=', _) | ('+', _) => Cmd::ZoomIn,
                    ('-', _) | ('_', _) => Cmd::ZoomOut,
                    ('0', false) => Cmd::ZoomReset,
                    ('q', false) => Cmd::Quit,
                    _ => return None,
                }
            } else if c(false, false, true) && ch == 'z' {
                Cmd::ToggleWrap
            } else {
                return None;
            }
        }
        Key::Tab if m.ctrl && !m.alt => {
            if m.shift { Cmd::PrevTab } else { Cmd::NextTab }
        }
        Key::PageDown if c(true, false, false) => Cmd::NextTab,
        Key::PageUp if c(true, false, false) => Cmd::PrevTab,
        Key::Up if c(false, false, true) => Cmd::MoveLineUp,
        Key::Down if c(false, false, true) => Cmd::MoveLineDown,
        Key::Left if c(true, false, true) => Cmd::FocusLeft,
        Key::Right if c(true, false, true) => Cmd::FocusRight,
        Key::Up if c(true, false, true) => Cmd::FocusUp,
        Key::Down if c(true, false, true) => Cmd::FocusDown,
        Key::F(1) if c(false, false, false) => Cmd::Palette,
        Key::F(3) if c(false, false, false) => Cmd::FindNext,
        Key::F(3) if c(false, true, false) => Cmd::FindPrev,
        Key::F(6) if c(false, false, false) => Cmd::FocusNextPane,
        Key::F(11) if c(false, false, false) => Cmd::Fullscreen,
        _ => return None,
    })
}
